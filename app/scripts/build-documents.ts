// Thin runner for the Documents-area generator. All real logic lives in
// documentsParser.ts as pure functions; this file is the only place that
// touches node:fs. Run with `npm run docs:build` from app/, or directly via
// `node app/scripts/build-documents.ts` from the repo root — Node v24
// (installed on this machine) runs plain .ts files natively, no devDependency
// needed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildDocumentsData, MANIFEST } from "./documentsParser.ts";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const FOUNDING_DIR = join(scriptDir, "../../docs/founding");
const OUTPUT_FILE = join(scriptDir, "../src/generated/documents.ts");

export function readAllFoundingMarkdown(): Record<string, string> {
  const founding: Record<string, string> = {};
  for (const file of Object.keys(MANIFEST)) {
    founding[file] = readFileSync(join(FOUNDING_DIR, file), "utf-8");
  }
  return founding;
}

/** Pure — takes markdown text in, returns the generated module's source text
 * out. The staleness test calls this directly and compares against the
 * committed file; no subprocess, no temp file, no overwrite-and-restore. */
export function renderModule(founding: Record<string, string>): string {
  const data = buildDocumentsData(founding);
  return [
    "// AUTO-GENERATED by app/scripts/build-documents.ts — do not hand-edit.",
    "// Source: docs/founding/*.md. Regenerate with `npm run docs:build` from app/",
    "// after editing those files. app/scripts/build-documents.test.ts fails if this",
    "// file goes stale relative to the source markdown.",
    `import type { DocumentsGenerated } from "../../scripts/documentsParser";`,
    "",
    `export const documentsData: DocumentsGenerated = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

const invokedDirectly = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (invokedDirectly) {
  writeFileSync(OUTPUT_FILE, renderModule(readAllFoundingMarkdown()));
  console.log(`Wrote ${OUTPUT_FILE}`);
}
